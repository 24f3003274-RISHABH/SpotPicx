// Helper functions
export function getAllIndiaStates(): IndiaStateData[] {
  return ALL_INDIA_STATES;
}

export function getIndiaStateBySlug(slug: string): IndiaStateData | undefined {
  if (!slug) return undefined;
  const normalized = slug.trim().toLowerCase();
  return ALL_INDIA_STATES.find(
    (s) => s.slug.toLowerCase() === normalized || s.name.toLowerCase().replace(/\s+/g, '-') === normalized
  );
}

export function getStatesByRegion(region: string): IndiaStateData[] {
  if (!region || region === 'All') return ALL_INDIA_STATES;
  return ALL_INDIA_STATES.filter((s) => s.region.toLowerCase() === region.toLowerCase());
}
