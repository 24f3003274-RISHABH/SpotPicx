export class ArticleService {
  /**
   * Get all published articles with optional category/tag filters
   */
  public static async getAllArticles(filters: { category?: string; tag?: string; location?: string; search?: string } = {}) {
    try {
      const query: any = { published: true };
      if (filters.category && filters.category !== 'all') {
        query.category = new RegExp(filters.category, 'i');
      }
      if (filters.tag) {
        query.tags = new RegExp(filters.tag, 'i');
      }
      if (filters.location) {
        query.locations = new RegExp(filters.location, 'i');
      }
      if (filters.search) {
        query.$or = [
          { title: new RegExp(filters.search, 'i') },
          { excerpt: new RegExp(filters.search, 'i') },
          { tags: new RegExp(filters.search, 'i') },
        ];
      }

      const dbArticles = await Article.find(query).sort({ publishedAt: -1, createdAt: -1 }).lean();
      if (dbArticles && dbArticles.length > 0) {
        return dbArticles;
      }
    } catch (e) {
      console.warn('DB Article find failed, returning curated fallback articles:', e);
    }

    // Curated fallback filter
    return curatedArticlesData.filter((art) => {
      if (filters.category && filters.category !== 'all') {
        if (!art.category.toLowerCase().includes(filters.category.toLowerCase())) return false;
      }
      if (filters.tag) {
        if (!art.tags.some((t) => t.toLowerCase().includes(filters.tag!.toLowerCase()))) return false;
      }
      if (filters.location) {
        if (!art.locations.some((l) => l.toLowerCase().includes(filters.location!.toLowerCase()))) return false;
      }
      if (filters.search) {
        const q = filters.search.toLowerCase();
        if (!art.title.toLowerCase().includes(q) && !art.excerpt.toLowerCase().includes(q)) return false;
      }
      return true;
    });
  }

  /**
   * Get a single article by slug
   */
  public static async getArticleBySlug(slug: string) {
    const cleanSlug = slug.toLowerCase().trim();
    try {
      const article = await Article.findOne({ slug: cleanSlug, published: true })
        .populate('relatedBusinesses')
        .lean();
      if (article) return article;
    } catch (e) {
      console.warn('Error fetching article from DB:', e);
    }

    return curatedArticlesData.find((a) => a.slug === cleanSlug) || null;
  }
}
